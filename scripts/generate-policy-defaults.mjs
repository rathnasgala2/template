#!/usr/bin/env node
/**
 * Regenerate `src/core/internal/policy-defaults-data.js` from the schemas
 * package's `site-policy-defaults` export, then format it:
 * `node scripts/generate-policy-defaults.mjs && npx prettier --write src/core/internal/policy-defaults-data.js`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const text = readFileSync(
  fileURLToPath(
    import.meta.resolve('@rathnasgala2/schemas/site-policy-defaults'),
  ),
  'utf8',
);
const target = new URL(
  '../src/core/internal/policy-defaults-data.js',
  import.meta.url,
);
writeFileSync(
  target,
  `/**
 * GENERATED by \`node scripts/generate-policy-defaults.mjs\` from
 * \`@rathnasgala2/schemas/site-policy-defaults\`; do not edit. The browser
 * preview reads no file, so it carries the shipped Terms and Privacy text as
 * a module; \`test/policy-defaults-data.test.js\` fails when this drifts from
 * the schemas package the build reads.
 */

export const SITE_POLICY_DEFAULTS_JSON = ${JSON.stringify(text)};
`,
);
