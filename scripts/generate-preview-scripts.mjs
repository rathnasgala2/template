#!/usr/bin/env node
/**
 * Regenerate `src/core/internal/preview-scripts-data.js` from the four
 * interactions browser scripts, then format it:
 * `node scripts/generate-preview-scripts.mjs && npx prettier --write src/core/internal/preview-scripts-data.js`.
 * The browser preview reads no file, so it carries the scripts' text as a
 * module; `test/preview-scripts-data.test.js` fails when this drifts from the
 * files the build writes.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const names = [
  'interactions',
  'counts',
  'signals',
  'audience',
  'video',
  'listen',
];
const entries = names.map((name) => {
  const text = readFileSync(
    new URL(
      `../src/modules/interactions/browser/gala-${name}.js`,
      import.meta.url,
    ),
    'utf8',
  );
  if (/<\/script|<!--|\r/i.test(text)) {
    throw new Error(`gala-${name}.js cannot be inlined in a <script>`);
  }
  return `  ${name}: ${JSON.stringify(text)},`;
});
writeFileSync(
  new URL('../src/core/internal/preview-scripts-data.js', import.meta.url),
  `/**
 * GENERATED by \`node scripts/generate-preview-scripts.mjs\` from
 * \`src/modules/interactions/browser/gala-*.js\`; do not edit. The text of each
 * script exactly as the build writes it, for the interactive preview to inline
 * (\`test/preview-scripts-data.test.js\` fails when this drifts).
 */

export const PREVIEW_SCRIPT_TEXTS = Object.freeze({
${entries.join('\n')}
});
`,
);
